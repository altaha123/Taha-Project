/* Writes frontend/glossary.html from the glossary inside index.html.

     node frontend/tools/build-glossary.cjs            write the page
     node frontend/tools/build-glossary.cjs --check    fail if it is out of date
     node frontend/tools/build-glossary.cjs --print    print it, write nothing

   WHY A PAGE AT ALL
   The glossary is a list in index.html's script (VOCAB) that a script draws
   when its tab is opened. A search engine reading the homepage finds none of
   it, and nobody can link to "what is ROCE". /glossary is the same terms as
   ordinary HTML at an address of their own, each with an anchor.

   WHY IT IS GENERATED
   Two copies of twenty-four definitions drift the first time one is edited.
   The terms stay where they are edited, in index.html; this prints the page
   from them, and backend/tests/test_seo_pages.py fails when the page no
   longer says what the list says. Edit a term, run this, commit both. */

'use strict';
const fs = require('node:fs'), path = require('node:path');

const front = path.resolve(__dirname, '..');
const SITE = 'https://altahascreener.in';
const out = path.join(front, 'glossary.html');

function terms() {
  const html = fs.readFileSync(path.join(front, 'index.html'), 'utf8');
  const m = /const VOCAB = \[([\s\S]*?)\n\];/.exec(html);
  if (!m) throw new Error('index.html no longer has `const VOCAB = [ ... ];`');
  // The list is a plain array literal of strings: nothing in it runs.
  return new Function('return [' + m[1] + '];')();
}

const esc = s => String(s == null ? '' : s)
  .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const slug = s => String(s).toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
// Safe inside <script>: with no "<" in it, nothing can close the element.
const json = o => JSON.stringify(o).replace(/</g, '\\u003c').replace(/>/g, '\\u003e');

function page(list) {
  const groups = [...new Set(list.map(v => v.g))];
  const url = SITE + '/glossary';
  const title = 'Stock market glossary: ROCE, ROE, Piotroski F-Score, pledging and more | Altaha Screener';
  const desc = 'Plain-English definitions of ' + list.length + ' stock market terms used on Altaha Screener, ' +
    'including ROCE, ROE, P/E, Piotroski F-Score, Mohanram G-Score, promoter pledging, Supertrend and OBV. ' +
    'Each has a worked example in rupees.';

  const ld = { '@context': 'https://schema.org', '@graph': [
    { '@type': 'BreadcrumbList', itemListElement: [
      { '@type': 'ListItem', position: 1, name: 'Altaha Screener', item: SITE + '/' },
      { '@type': 'ListItem', position: 2, name: 'Glossary', item: url }] },
    { '@type': 'DefinedTermSet', '@id': url, url: url, name: 'Altaha Screener stock market glossary',
      description: desc, inLanguage: 'en-IN',
      hasDefinedTerm: list.map(v => Object.assign(
        { '@type': 'DefinedTerm', '@id': url + '#' + slug(v.t), name: v.t },
        v.full ? { alternateName: v.full } : {},
        { description: v.s, url: url + '#' + slug(v.t), inDefinedTermSet: url })) }
  ] };

  // A group and a term can share a name ("Volume"), so a group's anchor is g-NAME.
  const toc = groups.map(g =>
    '<li><a href="#g-' + slug(g) + '">' + esc(g) + '</a><span>' +
    list.filter(v => v.g === g).map(v => '<a href="#' + slug(v.t) + '">' + esc(v.t) + '</a>').join(', ') +
    '</span></li>').join('\n      ');

  const body = groups.map(g =>
    '  <section class="doc-group" id="g-' + slug(g) + '">\n    <h2>' + esc(g) + '</h2>\n' +
    list.filter(v => v.g === g).map(v =>
      '    <article class="doc-term" id="' + slug(v.t) + '">\n' +
      '      <h3>' + esc(v.t) + (v.full ? ' <span>' + esc(v.full) + '</span>' : '') + '</h3>\n' +
      '      <p class="doc-def">' + esc(v.s) + '</p>\n' +
      '      <p><b>Example.</b> ' + esc(v.e) + '</p>\n' +
      '      <p><b>Why it matters.</b> ' + esc(v.w) + '</p>\n' +
      '    </article>').join('\n') +
    '\n  </section>').join('\n\n');

  return `<!doctype html>
<html lang="en" data-theme="light">
<head>
<meta charset="utf-8" /><script src="clean-url.js"></script>
<!-- GENERATED by tools/build-glossary.cjs from the VOCAB list in index.html.
     Edit the terms there and run it again; do not edit this file by hand. -->
<meta name="viewport" content="width=device-width, initial-scale=1" />
<title>${esc(title)}</title>
<meta name="description" content="${esc(desc)}" />
<meta name="robots" content="index,follow" />
<link rel="canonical" href="${url}" />
<meta property="og:type" content="article" />
<meta property="og:site_name" content="Altaha Screener" />
<meta property="og:title" content="${esc(title)}" />
<meta property="og:description" content="${esc(desc)}" />
<meta property="og:url" content="${url}" />
<meta property="og:image" content="${SITE}/icon-512.png" />
<script type="application/ld+json">${json(ld)}</script>
<link rel="icon" href="favicon.ico" sizes="any" />
<link rel="icon" type="image/png" href="icon-512.png" sizes="512x512" />
<link rel="apple-touch-icon" href="apple-touch-icon.png" />
<link rel="preconnect" href="https://fonts.googleapis.com">
<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
<link href="https://fonts.googleapis.com/css2?family=Instrument+Serif:ital@0;1&family=IBM+Plex+Mono:wght@400;500;600&family=Inter:wght@400;500;600&display=swap" rel="stylesheet">
<link rel="stylesheet" href="altaha-polish.css">
<link rel="stylesheet" href="altaha-skin.css">
<link rel="stylesheet" href="shell.css?v=20261113-foot">
<link rel="stylesheet" href="stock.css?v=20261120-seo">
<link rel="stylesheet" href="experience.css?v=20261015-doors">
<link rel="stylesheet" href="type.css">
<script>
  (function () {
    try {
      var s = localStorage.getItem('altaha-theme');
      var d = window.matchMedia && window.matchMedia('(prefers-color-scheme: dark)').matches;
      document.documentElement.setAttribute('data-theme', s || (d ? 'dark' : 'light'));
    } catch (e) {}
  })();
  var API_BASE = "https://taha-project.onrender.com";
</script>
<script src="analytics.js" defer></script>
<script src="auth.js" defer></script>
</head>
<body>
<main class="stk-wrap doc">
  <div class="stk-head">
    <div class="stk-crumb"><a href="./"><span class="brandmark" aria-hidden="true"></span><span>Altaha Screener</span></a> · <span>Glossary</span></div>
    <h1 class="stk-name">Stock market glossary, in plain English</h1>
    <p class="dir-sub">${list.length} terms the screener uses. Each has a one-line meaning, a worked example in rupees and the reason it matters. Nothing here is advice; it is what the words mean.</p>
  </div>

  <div class="doc-toc" data-nosnippet>
    <ul>
      ${toc}
    </ul>
  </div>

${body}

  <section class="doc-more">
    <h2>Where these are used</h2>
    <p>Every company page prints these figures from the company&rsquo;s own filings: see <a href="/stocks">all NSE companies, A to Z</a>. How they are combined into one number is on <a href="/methodology">how the Altaha Score works</a>. The same glossary, with a search box, is inside the screener: <a href="./#me/vocab">open it there</a>.</p>
  </section>
</main>
<script src="shell.js?v=20261120-seo" defer></script>
<script src="experience.js?v=20261118-pages" defer></script>
</body>
</html>
`;
}

const made = page(terms());
if (process.argv.includes('--print')) {
  process.stdout.write(made);
} else if (process.argv.includes('--check')) {
  const have = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : '';
  if (have !== made) {
    console.error('frontend/glossary.html is out of date: run node frontend/tools/build-glossary.cjs');
    process.exit(1);
  }
  console.log('glossary.html is up to date');
} else {
  fs.writeFileSync(out, made);
  console.log('wrote ' + path.relative(process.cwd(), out));
}
